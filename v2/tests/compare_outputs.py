"""Compare every output of two pipeline runs, e.g. a fresh setup against the
results in the repository:

    python v2/tests/compare_outputs.py <reference v2 folder> <new v2 folder> [out.csv]

Every file falls in exactly one class:
  identical           the bytes match
  same content        the content matches but the file stores write times or
                      the folder it ran in: DuckDB tables compared value by
                      value, Parquet by value, Word files part by part
                      (ignoring the zip container), logs with the folder path
                      removed
  run time only       the only differences are measured run times
                      (pipeline_timings.json; the run-time table and sentence
                      of the manuscript, in its Markdown and Word versions)
  kept in repository  not generated by the pipeline; checked for presence
  DIFFERENT           anything else, or a missing file
Exits with status 1 if any file is DIFFERENT.
"""
import hashlib
import re
import sys
import zipfile
from pathlib import Path

import duckdb
import pandas as pd

GENERATED = ["data/bronze/bbs", "data/bronze/manifest.csv", "data/silver", "data/gold", "mappings",
             "docs/data_dictionary.md", "outputs", "paper/reference.docx", "paper_ems/Manuscript_EMS.md",
             "paper_ems/Manuscript_EMS.docx", "paper_ems/Highlights.docx"]
TIMING_FILES = {"outputs/pipeline_timings.json"}
# Kept in the repository, not written by the pipeline: the dashboard screenshot
# and the record of the one-off Sentinel-1 single-band check (needs Earth Engine).
RECORDED = {"outputs/figures/fig7_dashboard.png", "outputs/failure_tests/s1_single_band_check.txt"}
RUN_TIME = re.compile(r"^\d+ s$")
IDENTICAL, SAME, RUNTIME, KEPT, DIFF = "identical", "same content", "run time only", "kept in repository", "DIFFERENT"


def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


def files(root):
    out = []
    for g in GENERATED:
        p = root / g
        out += [p] if p.is_file() else sorted(f for f in p.rglob("*") if f.is_file())
    return {f.relative_to(root).as_posix() for f in out}


def tables_equal(a, b):
    ca, cb = duckdb.connect(str(a), read_only=True), duckdb.connect(str(b), read_only=True)
    ta = sorted(t[0] for t in ca.execute("SHOW TABLES").fetchall())
    tb = sorted(t[0] for t in cb.execute("SHOW TABLES").fetchall())
    if ta != tb:
        return False, f"table lists differ: {ta} vs {tb}"
    bad = [t for t in ta if not ca.execute(f"SELECT * FROM {t}").df().equals(cb.execute(f"SELECT * FROM {t}").df())]
    return not bad, f"{len(ta)} tables, contents identical" if not bad else f"tables differ: {bad}"


def run_time_text(text):
    """A line or paragraph that reports measured run times: a cell of the
    run-time table, or the sentence that quotes the total run time."""
    t = text.strip()
    return bool(RUN_TIME.match(t)) or t.endswith(" s |") or "takes about" in t


def paragraphs(xml):
    return [re.sub(r"<[^>]+>", "", p) for p in re.findall(r"<w:p[ >].*?</w:p>", xml.decode("utf-8"), flags=re.S)]


def docx_equal(a, b):
    za, zb = zipfile.ZipFile(a), zipfile.ZipFile(b)
    parts = sorted(n for n in za.namelist() if not n.startswith("docProps/"))
    if parts != sorted(n for n in zb.namelist() if not n.startswith("docProps/")):
        return False, "different parts"
    bad = [n for n in parts if za.read(n) != zb.read(n)]
    if not bad:
        return SAME, "document parts identical (zip timestamps differ)"
    if bad != ["word/document.xml"]:
        return DIFF, f"parts differ: {bad}"
    pa, pb = paragraphs(za.read(bad[0])), paragraphs(zb.read(bad[0]))
    if len(pa) != len(pb):
        return DIFF, f"{len(pa)} vs {len(pb)} paragraphs"
    diff = [x for x, y in zip(pa, pb) if x != y]
    unexpected = [x for x in diff if not run_time_text(x)]
    if unexpected:
        return DIFF, f"unexpected differences: {unexpected[:3]}"
    return RUNTIME, f"{len(diff)} paragraphs differ, all run times"


def manuscript_lines(a, b):
    la, lb = a.read_text(encoding="utf-8").splitlines(), b.read_text(encoding="utf-8").splitlines()
    if len(la) != len(lb):
        return DIFF, f"{len(la)} vs {len(lb)} lines"
    diff = [(x, y) for x, y in zip(la, lb) if x != y]
    if not diff:
        return SAME, "same text (line endings differ)"
    unexpected = [x for x, _ in diff if not run_time_text(x)]
    if unexpected:
        return DIFF, f"unexpected differences: {unexpected[:3]}"
    return RUNTIME, f"{len(diff)} lines differ, all run times"


def main():
    ref, new = Path(sys.argv[1]).resolve(), Path(sys.argv[2]).resolve()
    out = Path(sys.argv[3]) if len(sys.argv) > 3 else None
    rows = []
    for rel in sorted(files(ref) | files(new)):
        a, b = ref / rel, new / rel
        if rel in RECORDED and a.exists() and b.exists():
            rows.append(dict(file=rel, status=KEPT, note="kept in the repository, not generated"))
            continue
        if not (a.exists() and b.exists()):
            rows.append(dict(file=rel, status=DIFF, note="missing in " + ("new" if a.exists() else "reference")))
            continue
        if sha(a) == sha(b):
            rows.append(dict(file=rel, status=IDENTICAL, note=""))
            continue
        if rel in TIMING_FILES:
            status, note = RUNTIME, "run times"
        elif a.suffix == ".duckdb":
            ok, note = tables_equal(a, b)
            status = SAME if ok else DIFF
        elif a.suffix == ".parquet":
            ok = pd.read_parquet(a).equals(pd.read_parquet(b))
            status, note = (SAME, "contents identical") if ok else (DIFF, "contents differ")
        elif a.suffix == ".docx":
            status, note = docx_equal(a, b)
        elif a.suffix == ".log":
            ta = a.read_text(encoding="utf-8").replace(str(ref), "<v2>")
            tb = b.read_text(encoding="utf-8").replace(str(new), "<v2>")
            status, note = (SAME, "identical apart from the folder path") if ta == tb else (DIFF, "contents differ")
        elif rel == "paper_ems/Manuscript_EMS.md":
            status, note = manuscript_lines(a, b)
        else:
            status, note = DIFF, "bytes differ"
        rows.append(dict(file=rel, status=status, note=note))
    df = pd.DataFrame(rows)
    if out:
        df.to_csv(out, index=False)
    print(df.status.value_counts().to_string())
    print(df[df.status != IDENTICAL].to_string(index=False))
    sys.exit(1 if (df.status == DIFF).any() else 0)


if __name__ == "__main__":
    main()
